//! Human and JSON rendering.

use std::io::{self, Write};

use anyhow::Result;
use tauten_check::{Diagnostic, Profile, Severity, Tier};

pub struct Options {
    pub json: bool,
    pub all_warnings: bool,
    pub baselined: u64,
}

pub fn print(diags: &[Diagnostic], options: &Options) -> Result<()> {
    let Options {
        json,
        all_warnings,
        baselined,
    } = *options;
    let stdout = io::stdout();
    let mut out = stdout.lock();
    if json {
        for d in diags {
            serde_json::to_writer(&mut out, d)?;
            writeln!(out)?;
        }
        return Ok(());
    }
    let shown = diags
        .iter()
        .filter(|d| all_warnings || d.severity == Severity::Error);
    for d in shown {
        let label = match d.severity {
            Severity::Error => "error",
            Severity::Warning => "warning",
        };
        let tier = d
            .tier
            .map_or_else(|| "untiered".to_owned(), |t| t.to_string());
        writeln!(out, "{label}[{}]: {}", d.id, d.message)?;
        let location = match (&d.file, d.line, d.column) {
            (Some(f), Some(l), Some(c)) => format!("{f}:{l}:{c}"),
            (Some(f), _, _) => f.clone(),
            _ => String::from("<workspace>"),
        };
        writeln!(out, "  --> {location} ({} crate `{}`)", tier, d.krate)?;
        if let Some(rule) = &d.rule {
            writeln!(out, "  = rule: {rule} (enforced by {:?})", d.enforced_by)?;
        }
        if let Some(fix) = &d.fix {
            writeln!(out, "  = fix: {fix}")?;
        }
        writeln!(out)?;
    }
    let errors = diags
        .iter()
        .filter(|d| d.severity == Severity::Error)
        .count();
    let warnings = diags.len().saturating_sub(errors);
    if !all_warnings && warnings > 0 {
        let mut by_rule: std::collections::BTreeMap<(&str, &str), usize> =
            std::collections::BTreeMap::new();
        for d in diags.iter().filter(|d| d.severity == Severity::Warning) {
            let slot = by_rule
                .entry((d.id.as_str(), d.rule.as_deref().unwrap_or("")))
                .or_insert(0);
            *slot = slot.saturating_add(1);
        }
        writeln!(out, "warnings (run with --warnings to list them):")?;
        for ((id, title), count) in by_rule {
            writeln!(out, "  {count:>6}  {id}  {title}")?;
        }
    }
    if baselined > 0 {
        writeln!(
            out,
            "tauten: {errors} error(s), {warnings} warning(s), {baselined} accepted by the baseline"
        )?;
    } else {
        writeln!(out, "tauten: {errors} error(s), {warnings} warning(s)")?;
    }
    Ok(())
}

pub fn explain(profile: &Profile, id: Option<&str>) -> Result<()> {
    let stdout = io::stdout();
    let mut out = stdout.lock();
    let Some(id) = id else {
        for rule in profile.rules() {
            writeln!(out, "{}  {}", rule.id, rule.title)?;
        }
        return Ok(());
    };
    let Some(rule) = profile.rule(id) else {
        anyhow::bail!("unknown rule `{id}`; run `cargo tauten explain` to list rules");
    };
    writeln!(out, "{}: {}\n", rule.id, rule.title)?;
    writeln!(out, "Why: {}\n", rule.why)?;
    writeln!(out, "Fix: {}\n", rule.fix)?;
    writeln!(out, "Enforced by: {:?}", rule.enforced_by)?;
    writeln!(
        out,
        "Applies to tests: {}",
        if rule.in_tests { "yes" } else { "no" }
    )?;
    writeln!(
        out,
        "Exceptions allowed: {}",
        if rule.exceptions {
            "with #[expect(.., reason)]"
        } else {
            "never"
        }
    )?;
    for tier in Tier::ALL {
        let level = level_name(rule.level(tier));
        writeln!(out, "  {tier:<6} {level}")?;
    }
    if !rule.lints.is_empty() {
        writeln!(out, "Lints: {}", rule.lints.join(", "))?;
    }
    for api in profile.api_bans().iter().filter(|a| a.rule == rule.id) {
        writeln!(out, "Banned ({}): {}", api.note, api.paths.join(", "))?;
    }
    Ok(())
}

pub fn profile(profile: &Profile, tier: Tier) -> Result<()> {
    let stdout = io::stdout();
    let mut out = stdout.lock();
    writeln!(
        out,
        "# lint flags for {tier}\n{}\n",
        profile.lint_flags(tier).join(" ")
    )?;
    writeln!(
        out,
        "# clippy.toml for {tier}\n{}",
        profile.clippy_toml(tier, false)?
    )?;
    Ok(())
}

fn level_name(level: Option<tauten_check::Level>) -> &'static str {
    match level {
        None => "-",
        Some(tauten_check::Level::Warn) => "warn",
        Some(tauten_check::Level::Deny) => "deny",
    }
}

/// The rule reference as Markdown; `docs/RULES.md` must equal this output.
pub fn rules_markdown(profile: &Profile) -> String {
    let mut md = String::from(
        "# Rule reference\n\n<!-- Generated by `cargo tauten explain --markdown`; do not edit. -->\n\n\
         | ID | Rule | kernel | core | edge | Tests | Exceptions | Enforced by |\n\
         |---|---|---|---|---|---|---|---|\n",
    );
    for rule in profile.rules() {
        md.push_str(&format!(
            "| [{id}](#{anchor}) | {title} | {k} | {c} | {e} | {tests} | {exc} | {by:?} |\n",
            id = rule.id,
            anchor = rule.id.to_ascii_lowercase(),
            title = rule.title,
            k = level_name(rule.level(Tier::Kernel)),
            c = level_name(rule.level(Tier::Core)),
            e = level_name(rule.level(Tier::Edge)),
            tests = if rule.in_tests { "yes" } else { "no" },
            exc = if rule.exceptions && rule.enforced_by != tauten_check::EnforcedBy::Tauten {
                "`#[expect]` + reason"
            } else {
                "never"
            },
            by = rule.enforced_by,
        ));
    }
    md.push_str(
        "\nIn `kernel` crates no profile rule admits exceptions (TAU-X004). \
         \"Tests: no\" means the rule is not applied to test targets.\n",
    );
    for rule in profile.rules() {
        md.push_str(&format!(
            "\n## {}\n\n**{}**\n\n{}\n\n**Fix:** {}\n",
            rule.id, rule.title, rule.why, rule.fix
        ));
        if !rule.lints.is_empty() {
            let lints: Vec<String> = rule.lints.iter().map(|l| format!("`{l}`")).collect();
            md.push_str(&format!("\nLints: {}\n", lints.join(", ")));
        }
        for api in profile.api_bans().iter().filter(|a| a.rule == rule.id) {
            let tiers: Vec<&str> = api.tiers.iter().map(|t| t.name()).collect();
            let paths: Vec<String> = api.paths.iter().map(|p| format!("`{p}`")).collect();
            md.push_str(&format!(
                "\nBanned in {} ({}): {}\n",
                tiers.join(", "),
                api.note,
                paths.join(", ")
            ));
        }
    }
    md
}
